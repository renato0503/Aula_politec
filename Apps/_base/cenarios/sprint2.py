    ir(pg, url, "#/requisicao/nova", 300)
    pg.fill("#paNumero", "2026.999999-9"); pg.fill("#paOrgao", "X"); pg.fill("#paTipo", "Y"); pg.fill("#paLocal", "Z")
    pg.click("#formPaNova button[type=submit]"); pg.wait_for_timeout(400)
